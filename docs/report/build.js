const t = (text, o = {}) => new TextRun({ text, font: FONT, size: 28, ...o });
function P(content, o = {}) {
  const runs = (Array.isArray(content) ? content : [content]).map(c => typeof c === 'string' ? t(c) : c);
  return new Paragraph({ children: runs, alignment: o.align ?? AlignmentType.JUSTIFIED,
    indent: o.noIndent ? undefined : { firstLine: 709 }, spacing: { line: 360, before: 0, after: o.after ?? 0 }, ...o.extra });
}
// «**жирный**» внутри строки
function rich(s) {
  const parts = s.split(/(\*\*[^*]+\*\*|`[^`]+`)/g).filter(Boolean);
  return parts.map(p => p.startsWith('**') ? t(p.slice(2, -2), { bold: true })
    : p.startsWith('`') ? new TextRun({ text: p.slice(1, -1), font: CODE, size: 24 }) : t(p));
}
